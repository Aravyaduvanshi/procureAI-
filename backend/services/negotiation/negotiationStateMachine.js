/**
 * ProcureAI Stateful Negotiation Engine State Machine
 * Defines valid states, permitted transitions, and approval gates.
 */

export const NEGOTIATION_STATES = {
  DRAFT: 'DRAFT',
  AWAITING_STRATEGY_APPROVAL: 'AWAITING_STRATEGY_APPROVAL',
  READY_FOR_MESSAGE_APPROVAL: 'READY_FOR_MESSAGE_APPROVAL',
  APPROVED_TO_SEND: 'APPROVED_TO_SEND',
  MESSAGE_SENT: 'MESSAGE_SENT',
  WAITING_FOR_SUPPLIER: 'WAITING_FOR_SUPPLIER',
  COUNTEROFFER_RECEIVED: 'COUNTEROFFER_RECEIVED',
  AWAITING_COUNTEROFFER_APPROVAL: 'AWAITING_COUNTEROFFER_APPROVAL',
  AGREED_SUBJECT_TO_FINAL_APPROVAL: 'AGREED_SUBJECT_TO_FINAL_APPROVAL',
  COMPLETED: 'COMPLETED',
  REJECTED: 'REJECTED',
  CANCELLED: 'CANCELLED'
};

const ALLOWED_TRANSITIONS = {
  [NEGOTIATION_STATES.DRAFT]: [
    NEGOTIATION_STATES.AWAITING_STRATEGY_APPROVAL,
    NEGOTIATION_STATES.CANCELLED
  ],
  [NEGOTIATION_STATES.AWAITING_STRATEGY_APPROVAL]: [
    NEGOTIATION_STATES.READY_FOR_MESSAGE_APPROVAL,
    NEGOTIATION_STATES.REJECTED,
    NEGOTIATION_STATES.CANCELLED
  ],
  [NEGOTIATION_STATES.READY_FOR_MESSAGE_APPROVAL]: [
    NEGOTIATION_STATES.APPROVED_TO_SEND,
    NEGOTIATION_STATES.AWAITING_STRATEGY_APPROVAL,
    NEGOTIATION_STATES.CANCELLED
  ],
  [NEGOTIATION_STATES.APPROVED_TO_SEND]: [
    NEGOTIATION_STATES.MESSAGE_SENT,
    NEGOTIATION_STATES.READY_FOR_MESSAGE_APPROVAL,
    NEGOTIATION_STATES.CANCELLED
  ],
  [NEGOTIATION_STATES.MESSAGE_SENT]: [
    NEGOTIATION_STATES.WAITING_FOR_SUPPLIER,
    NEGOTIATION_STATES.CANCELLED
  ],
  [NEGOTIATION_STATES.WAITING_FOR_SUPPLIER]: [
    NEGOTIATION_STATES.COUNTEROFFER_RECEIVED,
    NEGOTIATION_STATES.AGREED_SUBJECT_TO_FINAL_APPROVAL,
    NEGOTIATION_STATES.CANCELLED
  ],
  [NEGOTIATION_STATES.COUNTEROFFER_RECEIVED]: [
    NEGOTIATION_STATES.AWAITING_COUNTEROFFER_APPROVAL,
    NEGOTIATION_STATES.REJECTED,
    NEGOTIATION_STATES.CANCELLED
  ],
  [NEGOTIATION_STATES.AWAITING_COUNTEROFFER_APPROVAL]: [
    NEGOTIATION_STATES.READY_FOR_MESSAGE_APPROVAL,
    NEGOTIATION_STATES.AGREED_SUBJECT_TO_FINAL_APPROVAL,
    NEGOTIATION_STATES.REJECTED,
    NEGOTIATION_STATES.CANCELLED
  ],
  [NEGOTIATION_STATES.AGREED_SUBJECT_TO_FINAL_APPROVAL]: [
    NEGOTIATION_STATES.COMPLETED,
    NEGOTIATION_STATES.CANCELLED
  ],
  [NEGOTIATION_STATES.COMPLETED]: [],
  [NEGOTIATION_STATES.REJECTED]: [NEGOTIATION_STATES.DRAFT],
  [NEGOTIATION_STATES.CANCELLED]: [NEGOTIATION_STATES.DRAFT]
};

export function canTransition(currentState, targetState) {
  if (!ALLOWED_TRANSITIONS[currentState]) {
    return false;
  }
  return ALLOWED_TRANSITIONS[currentState].includes(targetState);
}

export function validateTransition(currentState, targetState) {
  if (currentState === targetState) {
    return { valid: true };
  }
  const allowed = canTransition(currentState, targetState);
  if (!allowed) {
    return {
      valid: false,
      error: `Invalid negotiation state transition from ${currentState} to ${targetState}. Permitted transitions: ${(ALLOWED_TRANSITIONS[currentState] || []).join(', ') || 'None'}`
    };
  }
  return { valid: true };
}
